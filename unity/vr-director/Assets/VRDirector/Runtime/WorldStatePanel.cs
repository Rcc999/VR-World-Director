using MixedReality.Toolkit.UX;
using TMPro;
using Unity.XR.CoreUtils;
using UnityEngine;

namespace VRDirector
{
    /// <summary>
    /// The World state panel (<see cref="WorldState"/>): the scene's caption and physics
    /// check, a SCENE row (Generated On / Off, Color Photo / Height / Depth, Gravity On / Off)
    /// and a REPLAY row (&lt; Run, Play: &lt;run&gt; / Stop, Run &gt;, Video RGB / Depth /
    /// Up field / Latitude); Close in the corner. The replay screen opens above the panel.
    /// Switching scenes is the Worlds panel's job (<see cref="WorldsPanel"/>).
    /// </summary>
    public class WorldStatePanel : MonoBehaviour
    {
        public XROrigin origin;
        public WorldState world;
        public TMP_FontAsset font;
        public Material backgroundMaterial;
        public PressableButton generated, colors, gravity, replay, prevRun, nextRun, layer, close;

        public const float Width = 0.62f, Height = 0.42f;
        public const float SceneRowY = -0.03f, ReplayRowY = -0.135f; // button rows (headers 36 mm above)

        public bool IsOpen => gameObject.activeSelf;

        TextMeshPro info;

        void Awake()
        {
            if (origin == null) origin = FindFirstObjectByType<XROrigin>();
            var bg = GameObject.CreatePrimitive(PrimitiveType.Quad);
            bg.name = "Background";
            Destroy(bg.GetComponent<Collider>());
            bg.transform.SetParent(transform, false);
            bg.transform.localScale = new Vector3(Width, Height, 1);
            bg.GetComponent<Renderer>().sharedMaterial = backgroundMaterial;

            info = new GameObject("Info").AddComponent<TextMeshPro>();
            info.transform.SetParent(transform, false);
            info.transform.localPosition = new Vector3(-0.04f, 0.1f, -0.005f); // left of the Close button
            info.font = font;
            info.enableAutoSizing = true; // captions vary in length
            info.fontSizeMin = 0.1f;
            info.fontSizeMax = 0.2f;
            info.alignment = TextAlignmentOptions.TopLeft;
            info.rectTransform.sizeDelta = new Vector2(Width - 0.12f, 0.14f);

            generated.OnClicked.AddListener(world.ToggleGenerated);
            colors.OnClicked.AddListener(world.CycleColors);
            gravity.OnClicked.AddListener(world.ToggleGravity);
            // The screen opens just above this panel, so it reads as part of it.
            replay.OnClicked.AddListener(() => world.ToggleReplay(transform.position + transform.up * (Height / 2 + 0.25f), transform.rotation));
            prevRun.OnClicked.AddListener(() => world.NextRun(-1));
            nextRun.OnClicked.AddListener(() => world.NextRun(1));
            layer.OnClicked.AddListener(world.CycleLayer);
            close.OnClicked.AddListener(Close);
            generated.enabled = world.HasGenerated;
            gameObject.SetActive(false);
        }

        public void Open()
        {
            var head = origin.Camera.transform;
            Vector3 fwd = Vector3.ProjectOnPlane(head.forward, Vector3.up).normalized;
            if (fwd.sqrMagnitude < 1e-4f) fwd = Vector3.forward;
            transform.SetPositionAndRotation(head.position + fwd * 0.55f - 0.15f * Vector3.up, // arm's reach
                                             Quaternion.LookRotation(fwd, Vector3.up));
            gameObject.SetActive(true);
        }

        public void Close() => gameObject.SetActive(false); // overlays and replay stay until turned off

        public void Toggle()
        {
            if (IsOpen) Close(); else Open();
        }

        void Update()
        {
            var run = world.CurrentRun;
            info.text = $"<b>{world.sceneName}</b>  <size=80%><color=#9ab>{KindName(world.kind)}</color></size>\n" +
                        $"<size=80%>{world.caption}</size>\n<size=75%><color=#9ab>{world.physicsCheck}</color></size>\n" +
                        (run == null ? "<size=80%>No camera runs</size>"
                            : $"<size=80%>Run {world.RunIndex + 1} of {world.runs.Length}: <b>{run.name}</b>, {run.views.Length} frames, " +
                              $"{(run.generated ? "generated by Puffin" : "real")}</size>");
            PathMenu.SetLabel(generated, !world.HasGenerated ? "All real" : world.ShowGenerated ? "Generated: On" : "Generated: Off");
            PathMenu.SetLabel(colors, $"Color: {world.Colors}");
            PathMenu.SetLabel(gravity, world.GravityShown ? "Gravity: On" : "Gravity: Off");
            PathMenu.SetLabel(replay, world.IsReplaying ? "Stop" : run == null ? "Play" : $"Play: {Short(run.name)}");
            PathMenu.SetLabel(layer, world.CurrentLayer switch
            {
                WorldState.Layer.UpField => "Video: Up field",
                WorldState.Layer.Latitude => "Video: Latitude",
                _ => $"Video: {world.CurrentLayer}",
            });
        }

        static string KindName(string kind) => kind switch
        {
            "single" => "one photo + Puffin",
            "multiseed" => "photos + Puffin",
            "real" => "real video",
            _ => kind,
        };

        /// <summary>Run names like "IMG_7017-left" shortened to fit a button.</summary>
        static string Short(string name) => name.Length <= 11 ? name : name.Substring(name.Length - 11);
    }
}
